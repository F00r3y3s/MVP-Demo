/**
 * Returns entities for a given sub-role, optionally filtered by a text query.
 * Matches name, shortName, and sector fields.
 */
export function findOrgEntities(subRole: OrgSubRole, query = ''): OrgEntity[] {
  const all = ORG_ENTITIES[subRole] ?? [];
  const q = query.trim().toLowerCase();
  if (!q) return all;
  return all.filter((e) => {
    const haystack = [e.name, e.shortName, e.sector, ...(e.emirate ? [e.emirate] : [])].join(' ').toLowerCase();
    return haystack.includes(q);
  });
}
